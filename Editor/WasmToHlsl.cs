using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace LogicCuteGuy.Wasm2Hlsl
{
    /// <summary>
    /// Translates a WebAssembly module into an HLSL function library plus a Blit shader per exported function.
    /// i32 → uint, i64 → uint2 (lo, hi), f32 → float, f64 → uint2 (IEEE double bits, software float), v128 → uint4,
    /// funcref/externref → uint (function index, 0xFFFFFFFF = null). Linear memory is a per-invocation
    /// static uint4 array, so it must be small (see <see cref="MaxMemoryBytes"/>).
    /// </summary>
    public static partial class WasmToHlsl
    {
        /// <summary>fxc caps temp + indexable registers at 4096 uint4s; keep ~96 for temps.</summary>
        public const uint MaxMemoryBytes = 4000 * 16;

        public static string TranslateLibrary(WasmModule m, string sourceName)
        {
            uint memBytes = MemoryBytes(m);
            var sb = new StringBuilder();
            sb.AppendLine($"// Generated by WASM2HLSL from {sourceName}. Do not edit; edit the .wasm instead.");
            sb.AppendLine("#ifndef WASM2HLSL_LIB");
            sb.AppendLine("#define WASM2HLSL_LIB");
            sb.AppendLine($"#define W_MEM_WORDS {memBytes / 4}u");
            sb.AppendLine($"#define W_MEM_PAGES {m.MemoryPages}u");
            sb.AppendLine("#ifndef W_MAX_LOOP_ITER");
            sb.AppendLine("#define W_MAX_LOOP_ITER 65536u // per loop entry; exceeding it sets the trap flag");
            sb.AppendLine("#endif");
            sb.AppendLine(MemoryDecl(m, memBytes));
            sb.Append(Prelude).Append(PreludeSimd);

            for (int i = 0; i < m.Globals.Count; i++)
            {
                var g = m.Globals[i];
                sb.AppendLine($"static {HT(g.Type)} g{i} = {Const(g.Type, g.Init, g.InitHi)};");
            }
            if (UsesInput(m))
                sb.AppendLine("Texture2D<float> _WasmInput; int _WasmInputWidth;\nuint w_input(uint i) { uint w = (uint)max(_WasmInputWidth, 1); return asuint(_WasmInput.Load(int3(i % w, i / w, 0))); }");

            // Emit every function body, then order callee-before-caller (HLSL needs it and forbids recursion).
            var nodes = new Dictionary<int, Node>();
            var usedDispatch = new HashSet<ulong>();
            var t = new TableUse();
            for (int i = 0; i < m.Bodies.Count; i++)
            {
                uint fi = (uint)(m.ImportedFuncCount + i);
                var e = new FuncEmitter(m, fi, t);
                try { e.Emit(); }
                catch (Exception ex) when (!(ex is WasmTranslateException))
                {
                    throw new WasmTranslateException($"Function {fi}: {ex.Message}", ex);
                }
                nodes[(int)fi] = new Node { Text = e.Text, Deps = e.Callees.Select(c => (int)c).Concat(e.Dispatches.Select(d => DispatchId(d))).ToList() };
                usedDispatch.UnionWith(e.Dispatches);
            }
            sb.Append(TableDecls(m, t));
            foreach (ulong d in usedDispatch)
            {
                var text = Dispatch(m, d, t, out var targets);
                nodes[DispatchId(d)] = new Node { Text = text, Deps = targets.Select(x => (int)x).ToList() };
            }

            var state = new Dictionary<int, int>();
            var ordered = new List<int>();
            foreach (int id in nodes.Keys.OrderBy(k => k)) Visit(id, nodes, state, ordered, m);
            foreach (int id in ordered) sb.AppendLine(nodes[id].Text);

            sb.AppendLine("#endif");
            return sb.ToString();
        }

        /// <summary>
        /// A Blit shader running one exported function per pixel. Output is int4(v, hi, trap, 0).
        /// R32 targets can stack planes vertically (AsyncGPUReadback only reads R32 int textures):
        /// rows [0, _WasmPlaneRows) give lo, plane _WasmHiPlane gives hi, plane _WasmTrapPlane gives the trap flag (0 = no such plane).
        /// </summary>
        public static string GenerateShader(WasmModule m, string exportName, string shaderName, string includeFile, string[] paramNames = null)
        {
            uint fi = m.FuncExports[exportName];
            var ft = m.TypeOfFunc(fi);
            if (ft.Results.Length > 1) throw new WasmTranslateException($"Export '{exportName}' returns multiple values.");

            var props = new StringBuilder();
            var uniforms = new StringBuilder();
            var args = new List<string>();
            for (int i = 0; i < ft.Params.Length; i++)
            {
                var t = ft.Params[i];
                if (i == 0 && t == WasmType.I32) { args.Add("id"); continue; }
                if (t == WasmType.V128) throw new WasmTranslateException($"Export '{exportName}' takes a v128; Udon can't pass one. Take scalars and build the vector inside.");
                bool isF = t == WasmType.F32 || t == WasmType.F64;
                string label = paramNames != null && i < paramNames.Length ? paramNames[i] : "Arg " + i;
                props.AppendLine($"        _WasmArg{i} (\"{label} ({t})\", {(isF ? "Float" : "Integer")}) = 0");
                uniforms.AppendLine($"            {(isF ? "float" : "int")} _WasmArg{i};");
                // f64 arguments arrive as float (Udon materials only take floats). Refs are a function index, -1 = null.
                args.Add(t == WasmType.F32 ? $"_WasmArg{i}" : t == WasmType.F64 ? $"w_f2d(_WasmArg{i})"
                    : t == WasmType.I64 ? $"uint2((uint)_WasmArg{i}, (uint)(_WasmArg{i} >> 31))" : $"(uint)_WasmArg{i}");
            }
            if (UsesInput(m)) props.AppendLine("        _WasmInput (\"Input (RFloat raw bits)\", 2D) = \"black\" {}\n        _WasmInputWidth (\"Input Width\", Integer) = 1");

            string call = $"f{fi}({string.Join(", ", args)})";
            string ret;
            if (ft.Results.Length == 0) ret = $"{call}; int lo = 0, hi = 0;";
            else switch (ft.Results[0])
            {
                case WasmType.I64: ret = $"uint2 r = {call}; int lo = asint(r.x), hi = asint(r.y);"; break;
                case WasmType.F64: ret = $"int lo = asint(w_d2f({call})), hi = 0;"; break; // read back as f32, like f32 exports
                case WasmType.V128: throw new WasmTranslateException($"Export '{exportName}' returns a v128; return a lane (i32x4.extract_lane) instead.");
                default: ret = $"int lo = asint({call}), hi = 0;"; break; // i32 / f32 bits / ref
            }

            return $@"// Generated by WASM2HLSL. Do not edit; edit the .wasm instead.
// One pixel = one invocation of '{exportName}'. Param 0 (if i32) receives the linear pixel index.
Shader ""{shaderName}""
{{
    Properties
    {{
        _WasmWidth (""Target Width"", Integer) = 1
        _WasmPlaneRows (""Rows Per Plane"", Integer) = 1073741824
        _WasmHiPlane (""Hi Plane"", Integer) = 0
        _WasmTrapPlane (""Trap Plane"", Integer) = 0
        _WasmBandRows (""Rows Per Band (0 = all)"", Integer) = 0
        _WasmBand (""Band"", Integer) = 0
{props}    }}
    SubShader
    {{
        Cull Off ZWrite Off ZTest Always
        Pass
        {{
            CGPROGRAM
            #pragma vertex vert_img
            #pragma fragment frag
            #pragma target 4.5
            #include ""UnityCG.cginc""
            int _WasmWidth, _WasmPlaneRows, _WasmHiPlane, _WasmTrapPlane, _WasmBandRows, _WasmBand;
{uniforms}            #include ""{includeFile}""

            int4 frag(v2f_img i) : SV_Target
            {{
                uint2 p = (uint2)i.pos.xy;
                if (_WasmBandRows > 0 && (int)(p.y / (uint)_WasmBandRows) != _WasmBand) discard; // other bands keep last frame's pixels
                uint rows = (uint)max(_WasmPlaneRows, 1);
                int plane = (int)(p.y / rows);
                uint id = p.x + (p.y - (uint)plane * rows) * (uint)max(_WasmWidth, 1);
                {ret}
                int v = plane != 0 && plane == _WasmTrapPlane ? (int)w_trap : plane != 0 && plane == _WasmHiPlane ? hi : lo;
                return int4(v, hi, (int)w_trap, 0);
            }}
            ENDCG
        }}
    }}
}}
";
        }

        // ---------------------------------------------------------------- module-level helpers

        sealed class Node { public string Text; public List<int> Deps; }

        /// <summary>call_indirect key: table index in the high word, type index in the low word.</summary>
        internal static ulong DispatchKey(uint typeIndex, uint table) => ((ulong)table << 32) | typeIndex;
        static int DispatchId(ulong key) => -1 - (int)((key >> 32) * 65536 + (key & 0xFFFF));

        static void Visit(int id, Dictionary<int, Node> nodes, Dictionary<int, int> state, List<int> order, WasmModule m)
        {
            if (!nodes.ContainsKey(id)) return; // imported function: inlined expression
            state.TryGetValue(id, out int s);
            if (s == 2) return;
            if (s == 1) throw new WasmTranslateException($"Recursion through {(id < 0 ? "call_indirect" : "function " + id)} — HLSL has no call stack. Rewrite it as a loop.");
            state[id] = 1;
            foreach (int d in nodes[id].Deps) Visit(d, nodes, state, order, m);
            state[id] = 2;
            order.Add(id);
        }

        /// <summary>
        /// call_indirect through one table. A table nothing writes dispatches on the slot; a written one reads w_tab
        /// and dispatches on the function index, over every function that can be a reference (table, elem segments, ref.func).
        /// </summary>
        static string Dispatch(WasmModule m, ulong key, TableUse use, out List<uint> targets)
        {
            uint typeIndex = (uint)key, table = (uint)(key >> 32);
            var ft = m.Types[(int)typeIndex];
            targets = new List<uint>();
            var ps = string.Join("", ft.Params.Select((t, i) => $", {HT(t)} a{i}"));
            var args = string.Join(", ", ft.Params.Select((t, i) => $"a{i}"));
            string ret = ft.Results.Length == 0 ? "void" : HT(ft.Results[0]);
            bool dynamic = use.Written.Contains(table);
            var init = m.Tables[(int)table].Init;
            var cases = dynamic
                ? init.Concat(m.Elems.SelectMany(e => e)).Concat(use.RefFuncs).Concat(m.GlobalRefFuncs)
                    .Where(f => f != uint.MaxValue).Distinct().OrderBy(f => f).Select(f => (key: f, f))
                : init.Select((f, s) => (key: (uint)s, f)).Where(c => c.f != uint.MaxValue);
            var sb = new StringBuilder();
            sb.AppendLine($"{ret} w_ci{typeIndex}_{table}(uint i{ps})");
            sb.AppendLine("{");
            if (ret != "void") sb.AppendLine($"    {ret} r = {Zero(ft.Results[0])};");
            if (dynamic) sb.AppendLine($"    i = w_tget{table}(i);");
            foreach (var (k, f) in cases)
            {
                if (!SameType(m.TypeOfFunc(f), ft)) continue;
                string call = m.FuncImport(f) is Import imp ? ImportExpr(imp, ft, ft.Params.Select((t, i) => $"a{i}").ToArray()) : $"f{f}({args})";
                if (!(m.FuncImport(f) is Import)) targets.Add(f);
                sb.AppendLine(ret == "void" ? $"    if (i == {k}u) {call};" : $"    if (i == {k}u) r = {call};").Append("    else");
            }
            sb.AppendLine(" w_trap = 1u;");
            if (ret != "void") sb.AppendLine("    return r;");
            sb.AppendLine("}");
            return sb.ToString();
        }

        /// <summary>What function bodies do with tables, collected while emitting them.</summary>
        internal sealed class TableUse
        {
            public readonly HashSet<uint> Used = new HashSet<uint>();    // need the w_tab array (get/set/fill/copy/init)
            public readonly HashSet<uint> Written = new HashSet<uint>(); // call_indirect must read the array
            public readonly HashSet<uint> RefFuncs = new HashSet<uint>();
            public readonly HashSet<uint> Elems = new HashSet<uint>();   // segments used by table.init / elem.drop
            public readonly HashSet<(uint dst, uint src)> Copies = new HashSet<(uint, uint)>();
            public readonly HashSet<(uint table, uint elem)> Inits = new HashSet<(uint, uint)>();
            public readonly HashSet<uint> Fills = new HashSet<uint>();
        }

        // ponytail: tables live in registers like memory; fine for the small tables compilers emit, not for thousands of slots.
        static string TableDecls(WasmModule m, TableUse u)
        {
            var sb = new StringBuilder();
            foreach (uint t in u.Used.OrderBy(x => x))
            {
                var init = m.Tables[(int)t].Init;
                uint n = (uint)init.Length;
                sb.AppendLine($"static uint w_tab{t}[{Math.Max(n, 1)}] = {{ {(n == 0 ? "0xFFFFFFFFu" : string.Join(", ", init.Select(f => U(f))))} }};");
                sb.AppendLine($"uint w_tget{t}(uint i) {{ if (i >= {n}u) w_trap = 1u; return i < {n}u ? w_tab{t}[i] : 0xFFFFFFFFu; }}");
                sb.AppendLine($"void w_tset{t}(uint i, uint v) {{ if (i < {n}u) w_tab{t}[i] = v; else w_trap = 1u; }}");
            }
            foreach (uint e in u.Elems.OrderBy(x => x))
            {
                var funcs = m.Elems[(int)e];
                sb.AppendLine($"static const uint w_elem{e}[{Math.Max(funcs.Length, 1)}] = {{ {(funcs.Length == 0 ? "0u" : string.Join(", ", funcs.Select(f => U(f))))} }};");
                sb.AppendLine($"static uint w_edrop{e} = 0u;");
            }
            foreach (var (t, e) in u.Inits)
            {
                uint n = (uint)m.Tables[(int)t].Init.Length, len = (uint)m.Elems[(int)e].Length;
                sb.AppendLine($"void w_tinit{t}_{e}(uint d, uint s, uint n) {{ if (s > {len}u || n > {len}u - s || d > {n}u || n > {n}u - d || (w_edrop{e} != 0u && n != 0u)) w_trap = 1u; " +
                              $"else {{ [loop] for (uint k = 0u; k < n; k++) w_tab{t}[d + k] = w_elem{e}[s + k]; }} }}");
            }
            foreach (var (x, y) in u.Copies)
            {
                uint nx = (uint)m.Tables[(int)x].Init.Length, ny = (uint)m.Tables[(int)y].Init.Length;
                sb.AppendLine($"void w_tcopy{x}_{y}(uint d, uint s, uint n) {{ if (s > {ny}u || n > {ny}u - s || d > {nx}u || n > {nx}u - d) w_trap = 1u; " +
                              $"else if (d <= s) {{ [loop] for (uint k = 0u; k < n; k++) w_tab{x}[d + k] = w_tab{y}[s + k]; }} " +
                              $"else {{ [loop] for (uint k = n; k > 0u; k--) w_tab{x}[d + k - 1u] = w_tab{y}[s + k - 1u]; }} }}");
            }
            foreach (uint t in u.Fills)
            {
                uint n = (uint)m.Tables[(int)t].Init.Length;
                sb.AppendLine($"void w_tfill{t}(uint i, uint v, uint n) {{ if (i > {n}u || n > {n}u - i) w_trap = 1u; else {{ [loop] for (uint k = 0u; k < n; k++) w_tab{t}[i + k] = v; }} }}");
            }
            return sb.ToString();
        }

        static bool SameType(FuncType a, FuncType b) => a.Params.SequenceEqual(b.Params) && a.Results.SequenceEqual(b.Results);

        static bool UsesInput(WasmModule m) => m.Imports.Any(i => i.Kind == 0 && (i.Name == "input" || i.Name == "hlsl_input"));

        /// <summary>
        /// Memory actually backed by registers: data end and any i32 global that looks like an address
        /// (stack pointer / heap base). Declared pages are ignored because one page already exceeds fxc's limit.
        /// </summary>
        public static uint MemoryBytes(WasmModule m)
        {
            if (!m.HasMemory) return 16;
            ulong need = 16;
            foreach (var d in m.Data) need = Math.Max(need, (ulong)d.Offset + (ulong)d.Bytes.Length);
            ulong pageBytes = (ulong)m.MemoryPages * 65536;
            foreach (var g in m.Globals)
                if (g.Type == WasmType.I32 && g.Init <= pageBytes) need = Math.Max(need, g.Init);
            // ponytail: no heap headroom; kernels using a bump allocator past __heap_base read 0 / drop writes.
            need = (need + 15) & ~15UL;
            if (need > MaxMemoryBytes)
                throw new WasmTranslateException(
                    $"Module needs {need} bytes of linear memory but the GPU limit is {MaxMemoryBytes}. " +
                    "Shrink the stack (Rust: -C link-arg=-zstack-size=4096) and static data.");
            return (uint)need;
        }

        static string MemoryDecl(WasmModule m, uint memBytes)
        {
            var bytes = new byte[memBytes];
            foreach (var d in m.Data)
                Array.Copy(d.Bytes, 0, bytes, d.Offset, Math.Min(d.Bytes.Length, (int)Math.Max(0, memBytes - d.Offset)));
            var sb = new StringBuilder($"static uint4 w_mem[{memBytes / 16}] = {{");
            for (int i = 0; i < bytes.Length; i += 16)
            {
                if (i % 64 == 0) sb.Append("\n    ");
                sb.Append("uint4(");
                for (int k = 0; k < 4; k++)
                {
                    uint w = BitConverter.ToUInt32(bytes, i + k * 4);
                    sb.Append(w == 0 ? "0u" : $"0x{w:X}u").Append(k < 3 ? "," : ")");
                }
                if (i + 16 < bytes.Length) sb.Append(", ");
            }
            sb.Append("\n};");
            return sb.ToString();
        }

        // ---------------------------------------------------------------- type / constant helpers

        internal static string HT(WasmType t)
        {
            switch (t)
            {
                case WasmType.I32: case WasmType.FuncRef: case WasmType.ExternRef: return "uint";
                case WasmType.I64: case WasmType.F64: return "uint2";
                case WasmType.F32: return "float";
                case WasmType.V128: return "uint4";
                default: throw new NotSupportedException($"Value type 0x{(byte)t:X2} is not supported.");
            }
        }

        internal static string Zero(WasmType t)
        {
            switch (t)
            {
                case WasmType.I32: return "0u";
                case WasmType.FuncRef: case WasmType.ExternRef: return "0xFFFFFFFFu"; // null
                case WasmType.I64: case WasmType.F64: return "uint2(0u, 0u)";
                case WasmType.V128: return "uint4(0u, 0u, 0u, 0u)";
                default: return "0.0f";
            }
        }

        internal static string Const(WasmType t, ulong bits, ulong hi = 0)
        {
            switch (t)
            {
                case WasmType.I32: case WasmType.FuncRef: case WasmType.ExternRef: return U((uint)bits);
                case WasmType.I64: case WasmType.F64: return $"uint2({U((uint)bits)}, {U((uint)(bits >> 32))})";
                case WasmType.V128: return $"uint4({U((uint)bits)}, {U((uint)(bits >> 32))}, {U((uint)hi)}, {U((uint)(hi >> 32))})";
                default: return F((uint)bits);
            }
        }

        internal static string U(uint v) => v < 1024 ? $"{v}u" : $"0x{v:X}u";

        static string F(uint bits)
        {
            float f = BitConverter.ToSingle(BitConverter.GetBytes(bits), 0);
            // Exact integers read better as literals; everything else keeps exact bits.
            if (!float.IsNaN(f) && !float.IsInfinity(f) && f == Math.Floor(f) && Math.Abs(f) < 1e7f && !(f == 0 && bits != 0))
                return f.ToString("0.0", CultureInfo.InvariantCulture) + "f";
            return $"asfloat(0x{bits:X8}u)";
        }

        internal static string ImportExpr(Import imp, FuncType ft, string[] a)
        {
            // Math runs in f32: f64 arguments are rounded to float and the result widened back.
            a = a.Select((x, i) => ft.Params[i] == WasmType.F64 ? $"w_d2f({x})" : x).ToArray();
            string e = ImportExpr(imp, a);
            return ft.Results.Length == 1 && ft.Results[0] == WasmType.F64 ? $"w_f2d({e})" : e;
        }

        static string ImportExpr(Import imp, string[] a)
        {
            // `hlsl_sin` etc. avoid clashing with libm symbols that Rust's compiler_builtins already defines.
            string n = imp.Name.StartsWith("hlsl_") ? imp.Name.Substring(5) : imp.Name;
            if (n == "input") return $"w_input({a[0]})";
            string Fn1(string f) => $"{f}({a[0]})";
            switch (n.EndsWith("f") && n.Length > 3 ? n.Substring(0, n.Length - 1) : n)
            {
                case "sin": case "cos": case "tan": case "asin": case "acos": case "atan":
                case "sinh": case "cosh": case "tanh": case "exp": case "exp2": case "log": case "log2": case "log10":
                case "sqrt": case "floor": case "ceil": case "trunc": case "round":
                    return Fn1(n.EndsWith("f") && n.Length > 3 ? n.Substring(0, n.Length - 1) : n);
                case "fabs": return Fn1("abs");
                case "pow": return $"pow({a[0]}, {a[1]})";
                case "atan2": return $"atan2({a[0]}, {a[1]})";
                case "fmod": return $"fmod({a[0]}, {a[1]})";
                case "fmin": return $"min({a[0]}, {a[1]})";
                case "fmax": return $"max({a[0]}, {a[1]})";
            }
            throw new WasmTranslateException($"Unsupported import '{imp.Module}.{imp.Name}'. Supported: input(i32)->i32 and math (hlsl_sin, hlsl_pow, sinf, ...).");
        }

        // ---------------------------------------------------------------- runtime prelude

        // Helpers are single-exit on purpose: fxc inlines everything, and early returns inside loops blow up compile time.
        const string Prelude = @"
static uint w_trap = 0u;

uint w_rd(uint i) { uint4 q = w_mem[min(i >> 2, W_MEM_WORDS / 4u - 1u)]; uint c = i & 3u; uint v = c == 0u ? q.x : c == 1u ? q.y : c == 2u ? q.z : q.w; return i < W_MEM_WORDS ? v : 0u; }
void w_wr(uint i, uint v) { if (i < W_MEM_WORDS) { uint4 q = w_mem[i >> 2]; uint c = i & 3u; w_mem[i >> 2] = uint4(c == 0u ? v : q.x, c == 1u ? v : q.y, c == 2u ? v : q.z, c == 3u ? v : q.w); } }
uint w_ld32(uint a) { uint s = (a & 3u) * 8u; uint lo = w_rd(a >> 2); uint hi = w_rd((a >> 2) + 1u); return s == 0u ? lo : (lo >> s) | (hi << (32u - s)); }
uint w_ld8(uint a) { return (w_rd(a >> 2) >> ((a & 3u) * 8u)) & 0xFFu; }
uint w_ld16(uint a) { return w_ld32(a) & 0xFFFFu; }
uint2 w_ld64(uint a) { return uint2(w_ld32(a), w_ld32(a + 4u)); }
void w_st8(uint a, uint v) { uint i = a >> 2; uint s = (a & 3u) * 8u; w_wr(i, (w_rd(i) & ~(0xFFu << s)) | ((v & 0xFFu) << s)); }
void w_st16(uint a, uint v)
{
    if ((a & 1u) == 0u) { uint i = a >> 2; uint s = (a & 2u) * 8u; w_wr(i, (w_rd(i) & ~(0xFFFFu << s)) | ((v & 0xFFFFu) << s)); }
    else { w_st8(a, v); w_st8(a + 1u, v >> 8); }
}
void w_st32(uint a, uint v) { if ((a & 3u) == 0u) w_wr(a >> 2, v); else { w_st16(a, v); w_st16(a + 2u, v >> 16); } }
void w_st64(uint a, uint2 v) { w_st32(a, v.x); w_st32(a + 4u, v.y); }
void w_fill(uint d, uint v, uint n) { [loop] for (uint k = 0u; k < n; k++) w_st8(d + k, v); }
void w_copy(uint d, uint s, uint n)
{
    if (d <= s) { [loop] for (uint k = 0u; k < n; k++) w_st8(d + k, w_ld8(s + k)); }
    else { [loop] for (uint k = n; k > 0u; k--) w_st8(d + k - 1u, w_ld8(s + k - 1u)); }
}

bool w_isnan(float f) { return (asuint(f) & 0x7FFFFFFFu) > 0x7F800000u; }
uint w_clz(uint x) { return x == 0u ? 32u : 31u - firstbithigh(x); }
uint w_ctz(uint x) { return x == 0u ? 32u : firstbitlow(x); }
uint w_rotl(uint x, uint n) { n &= 31u; return n == 0u ? x : (x << n) | (x >> (32u - n)); }
uint w_rotr(uint x, uint n) { n &= 31u; return n == 0u ? x : (x >> n) | (x << (32u - n)); }
uint w_divu(uint a, uint b) { if (b == 0u) w_trap = 1u; return b == 0u ? 0u : a / b; }
uint w_remu(uint a, uint b) { if (b == 0u) w_trap = 1u; return b == 0u ? 0u : a % b; }
uint w_divs(uint a, uint b)
{
    if (b == 0u) w_trap = 1u;
    uint ua = (int)a < 0 ? 0u - a : a; uint ub = (int)b < 0 ? 0u - b : b;
    uint q = ub == 0u ? 0u : ua / ub; return ((a ^ b) & 0x80000000u) != 0u ? 0u - q : q;
}
uint w_rems(uint a, uint b)
{
    if (b == 0u) w_trap = 1u;
    uint ua = (int)a < 0 ? 0u - a : a; uint ub = (int)b < 0 ? 0u - b : b;
    uint r = ub == 0u ? 0u : ua % ub; return (int)a < 0 ? 0u - r : r;
}
float w_copysign(float a, float b) { return asfloat((asuint(a) & 0x7FFFFFFFu) | (asuint(b) & 0x80000000u)); }
float w_nearest(float f) { return round(f); }
uint w_trunc_s(float f)
{
    float t = trunc(f);
