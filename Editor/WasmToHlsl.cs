// trunc(|a|) as u64; big when |a| >= 2^64 (inf and NaN included).
uint2 w_dmag(uint2 a, out bool big)
{
    int e = (int)w_dexp(a) - 1023;
    uint2 m = w_dfrac(a) | uint2(0u, 0x00100000u);
    big = e >= 64;
    return e < 0 ? uint2(0u, 0u) : e <= 52 ? w_shru64(m, (uint)(52 - e)) : w_shl64(m, (uint)min(e - 52, 63));
}
// f64 -> int truncation saturates (NaN -> 0), like the f32 ones.
uint w_dtrunc_u(uint2 a) { bool big; uint2 m = w_dmag(a, big); return w_disnan(a) || (a.y >> 31) != 0u ? 0u : big || m.y != 0u ? 0xFFFFFFFFu : m.x; }
uint w_dtrunc_s(uint2 a)
{
    bool big; uint2 m = w_dmag(a, big);
    bool over = big || m.y != 0u;
    return w_disnan(a) ? 0u : (a.y >> 31) != 0u ? (over || m.x > 0x80000000u ? 0x80000000u : 0u - m.x) : (over || m.x > 0x7FFFFFFFu ? 0x7FFFFFFFu : m.x);
}
uint2 w_dtrunc_u64(uint2 a) { bool big; uint2 m = w_dmag(a, big); return w_disnan(a) || (a.y >> 31) != 0u ? uint2(0u, 0u) : big ? uint2(0xFFFFFFFFu, 0xFFFFFFFFu) : m; }
uint2 w_dtrunc_s64(uint2 a)
