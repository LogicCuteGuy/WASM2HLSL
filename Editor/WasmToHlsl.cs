uint2 w_sext64(uint lo) { return uint2(lo, (uint)((int)lo >> 31)); }
// Bitwise carry: fxc miscompiles the usual `(a + b) < a` overflow test when b is a constant.
uint2 w_add64(uint2 a, uint2 b) { uint lo = a.x + b.x; uint c = ((a.x & b.x) | ((a.x | b.x) & ~lo)) >> 31; return uint2(lo, a.y + b.y + c); }
uint2 w_sub64(uint2 a, uint2 b) { return uint2(a.x - b.x, a.y - b.y - (a.x < b.x ? 1u : 0u)); }
uint2 w_neg64(uint2 a) { return w_sub64(uint2(0u, 0u), a); }
uint2 w_mulu32(uint a, uint b)
{
    uint al = a & 0xFFFFu, ah = a >> 16, bl = b & 0xFFFFu, bh = b >> 16;
    uint ll = al * bl, lh = al * bh, hl = ah * bl, hh = ah * bh;
    uint mid = (ll >> 16) + (lh & 0xFFFFu) + (hl & 0xFFFFu);
    return uint2((ll & 0xFFFFu) | (mid << 16), hh + (lh >> 16) + (hl >> 16) + (mid >> 16));
}
uint2 w_mul64(uint2 a, uint2 b) { uint2 p = w_mulu32(a.x, b.x); p.y += a.x * b.y + a.y * b.x; return p; }
uint2 w_shl64(uint2 a, uint n)
{
    n &= 63u;
    return n == 0u ? a : n >= 32u ? uint2(0u, a.x << (n - 32u)) : uint2(a.x << n, (a.y << n) | (a.x >> (32u - n)));
}
uint2 w_shru64(uint2 a, uint n)
{
    n &= 63u;
    return n == 0u ? a : n >= 32u ? uint2(a.y >> (n - 32u), 0u) : uint2((a.x >> n) | (a.y << (32u - n)), a.y >> n);
}
uint2 w_shrs64(uint2 a, uint n)
{
    n &= 63u;
    return n == 0u ? a : n >= 32u ? uint2((uint)((int)a.y >> (n - 32u)), (uint)((int)a.y >> 31))
        : uint2((a.x >> n) | (a.y << (32u - n)), (uint)((int)a.y >> n));
}
uint2 w_rotl64(uint2 a, uint n) { n &= 63u; return n == 0u ? a : (w_shl64(a, n) | w_shru64(a, 64u - n)); }
uint2 w_rotr64(uint2 a, uint n) { n &= 63u; return n == 0u ? a : (w_shru64(a, n) | w_shl64(a, 64u - n)); }
bool w_ltu64(uint2 a, uint2 b) { return a.y < b.y || (a.y == b.y && a.x < b.x); }
bool w_lts64(uint2 a, uint2 b) { return (int)a.y < (int)b.y || (a.y == b.y && a.x < b.x); }
uint2 w_clz64(uint2 a) { return uint2(a.y != 0u ? w_clz(a.y) : 32u + w_clz(a.x), 0u); }
uint2 w_ctz64(uint2 a) { return uint2(a.x != 0u ? w_ctz(a.x) : 32u + w_ctz(a.y), 0u); }
uint2 w_divmodu64(uint2 n, uint2 d, out uint2 r)
{
    uint2 q = uint2(0u, 0u);
    r = uint2(0u, 0u);
    if (d.x == 0u && d.y == 0u) w_trap = 1u;
    else if (n.y == 0u && d.y == 0u) { q = uint2(n.x / d.x, 0u); r = uint2(n.x % d.x, 0u); }
    else
    {
        [loop] for (int i = 63; i >= 0; i--)
        {
            r = w_shl64(r, 1u);
            r.x |= (i >= 32 ? (n.y >> (uint)(i - 32)) : (n.x >> (uint)i)) & 1u;
            if (!w_ltu64(r, d)) { r = w_sub64(r, d); if (i >= 32) q.y |= 1u << (uint)(i - 32); else q.x |= 1u << (uint)i; }
        }
    }
    return q;
}
uint2 w_divu64(uint2 a, uint2 b) { uint2 r; return w_divmodu64(a, b, r); }
uint2 w_remu64(uint2 a, uint2 b) { uint2 r; w_divmodu64(a, b, r); return r; }
uint2 w_abs64(uint2 a) { return (int)a.y < 0 ? w_neg64(a) : a; }
uint2 w_divs64(uint2 a, uint2 b) { uint2 q = w_divu64(w_abs64(a), w_abs64(b)); return ((a.y ^ b.y) & 0x80000000u) != 0u ? w_neg64(q) : q; }
uint2 w_rems64(uint2 a, uint2 b) { uint2 r = w_remu64(w_abs64(a), w_abs64(b)); return (int)a.y < 0 ? w_neg64(r) : r; }
float w_cvt_u64(uint2 a) { return (float)a.y * 4294967296.0f + (float)a.x; }
float w_cvt_s64(uint2 a) { return (int)a.y < 0 ? -w_cvt_u64(w_neg64(a)) : w_cvt_u64(a); }
uint2 w_trunc_u64(float f)
{
    float t = trunc(f);
    float h = floor(t * asfloat(0x2F800000u));
    uint2 v = uint2((uint)(t - h * 4294967296.0f), (uint)h);
    return (w_isnan(f) || f <= 0.0f) ? uint2(0u, 0u) : t >= asfloat(0x5F800000u) ? uint2(0xFFFFFFFFu, 0xFFFFFFFFu) : v;
}
uint2 w_trunc_s64(float f)
{
    uint2 neg = f <= asfloat(0xDF000000u) ? uint2(0u, 0x80000000u) : w_neg64(w_trunc_u64(-f));
    uint2 pos = f >= asfloat(0x5F000000u) ? uint2(0xFFFFFFFFu, 0x7FFFFFFFu) : w_trunc_u64(f);
    return w_isnan(f) ? uint2(0u, 0u) : f < 0.0f ? neg : pos;
}
// ---- f64: IEEE double bits in a uint2 (x = low word), software float rounding to nearest even (SoftFloat's algorithms).
uint w_clz64u(uint2 a) { return a.y != 0u ? w_clz(a.y) : 32u + w_clz(a.x); }
bool w_nz64(uint2 a) { return (a.x | a.y) != 0u; }
// Shift right, OR-ing every lost bit into bit 0.
uint2 w_jam64(uint2 a, uint n)
{
    uint2 r = n >= 64u ? uint2(0u, 0u) : w_shru64(a, n);
    r.x |= any(w_shl64(r, min(n, 63u)) != a) ? 1u : 0u;
    return r;
}
uint w_dexp(uint2 a) { return (a.y >> 20) & 0x7FFu; }
uint2 w_dfrac(uint2 a) { return uint2(a.x, a.y & 0xFFFFFu); }
bool w_disnan(uint2 a) { return w_dexp(a) == 0x7FFu && w_nz64(w_dfrac(a)); }
bool w_dzero(uint2 a) { return (a.x | (a.y & 0x7FFFFFFFu)) == 0u; }
uint2 w_dinf(uint s) { return uint2(0u, (s << 31) | 0x7FF00000u); }
uint2 w_dnan(uint2 a, uint2 b) { return (w_disnan(a) ? a : b) | uint2(0u, 0x00080000u); }
static const uint2 W_DNAN = uint2(0u, 0x7FF80000u);
// sign, exponent, significand added (not OR-ed) so a carry out of the significand bumps the exponent.
uint2 w_dpack(uint s, uint e, uint2 sig) { return w_add64(uint2(0u, (s << 31) + (e << 20)), sig); }
// sig has its leading 1 at bit 62; e is the biased exponent minus one.
uint2 w_dround(uint s, int e, uint2 sig)
{
    bool ovf = false;
    if (e < 0) { sig = w_jam64(sig, (uint)(-e)); e = 0; }
    else if (e > 2045 || (e == 2045 && w_add64(sig, uint2(0x200u, 0u)).y >= 0x80000000u)) ovf = true;
    uint rb = sig.x & 0x3FFu;
    sig = w_shru64(w_add64(sig, uint2(0x200u, 0u)), 10u);
    if (rb == 0x200u) sig.x &= ~1u;
    if (!w_nz64(sig)) e = 0;
    return ovf ? w_dinf(s) : w_dpack(s, (uint)e, sig);
}
uint2 w_dnormround(uint s, int e, uint2 sig)
{
    int sh = (int)w_clz64u(sig) - 1;
    e -= sh;
    return sh >= 10 && (uint)e < 0x7FDu ? w_dpack(s, w_nz64(sig) ? (uint)e : 0u, w_shl64(sig, (uint)(sh - 10)))
        : w_dround(s, e, w_shl64(sig, (uint)sh));
}
// Moves a subnormal's leading 1 to bit 52.
void w_dnorm(inout int e, inout uint2 m) { if (e == 0) { int sh = (int)w_clz64u(m) - 11; e = 1 - sh; m = w_shl64(m, (uint)sh); } }
uint2 w_daddmags(uint2 a, uint2 b, uint s)
{
    int ea = (int)w_dexp(a), eb = (int)w_dexp(b);
    uint2 ma = w_dfrac(a), mb = w_dfrac(b), r = uint2(0u, 0u);
    int d = ea - eb;
    if (d == 0)
    {
        if (ea == 0) r = w_add64(a, mb);
        else if (ea == 2047) r = w_nz64(ma | mb) ? w_dnan(a, b) : a;
        else r = w_dround(s, ea, w_shl64(w_add64(w_add64(uint2(0u, 0x00200000u), ma), mb), 9u));
    }
    else
    {
        bool done = false; int ez = 0;
        ma = w_shl64(ma, 9u); mb = w_shl64(mb, 9u);
        if (d < 0)
        {
            if (eb == 2047) { done = true; r = w_nz64(mb) ? w_dnan(a, b) : w_dinf(s); }
            ez = eb;
            ma = w_jam64(ea != 0 ? w_add64(ma, uint2(0u, 0x20000000u)) : w_shl64(ma, 1u), (uint)(-d));
        }
        else
        {
            if (ea == 2047) { done = true; r = w_nz64(ma) ? w_dnan(a, b) : a; }
            ez = ea;
            mb = w_jam64(eb != 0 ? w_add64(mb, uint2(0u, 0x20000000u)) : w_shl64(mb, 1u), (uint)d);
        }
        uint2 z = w_add64(w_add64(uint2(0u, 0x20000000u), ma), mb);
        if (z.y < 0x40000000u) { ez--; z = w_shl64(z, 1u); }
        if (!done) r = w_dround(s, ez, z);
    }
    return r;
}
uint2 w_dsubmags(uint2 a, uint2 b, uint s)
{
    int ea = (int)w_dexp(a), eb = (int)w_dexp(b);
    uint2 ma = w_dfrac(a), mb = w_dfrac(b), r = uint2(0u, 0u);
    int d = ea - eb;
    if (d == 0)
    {
        if (ea == 2047) r = w_nz64(ma | mb) ? w_dnan(a, b) : W_DNAN;
        else
        {
            uint2 diff = w_sub64(ma, mb);
            if (w_nz64(diff))
            {
                if (ea != 0) ea--;
                if ((int)diff.y < 0) { s ^= 1u; diff = w_neg64(diff); }
                int sh = (int)w_clz64u(diff) - 11;
                int ez = ea - sh;
                if (ez < 0) { sh = ea; ez = 0; }
                r = w_dpack(s, (uint)ez, w_shl64(diff, (uint)sh));
            }
        }
    }
    else
    {
        bool done = false; int ez = 0; uint2 z = uint2(0u, 0u);
        ma = w_shl64(ma, 10u); mb = w_shl64(mb, 10u);
        if (d < 0)
        {
            s ^= 1u;
            if (eb == 2047) { done = true; r = w_nz64(mb) ? w_dnan(a, b) : w_dinf(s); }
            ma = w_jam64(w_add64(ma, ea != 0 ? uint2(0u, 0x40000000u) : ma), (uint)(-d));
            mb.y |= 0x40000000u;
            ez = eb; z = w_sub64(mb, ma);
        }
        else
        {
            if (ea == 2047) { done = true; r = w_nz64(ma) ? w_dnan(a, b) : a; }
            mb = w_jam64(w_add64(mb, eb != 0 ? uint2(0u, 0x40000000u) : mb), (uint)d);
            ma.y |= 0x40000000u;
            ez = ea; z = w_sub64(ma, mb);
        }
        if (!done) r = w_dnormround(s, ez - 1, z);
    }
    return r;
}
uint2 w_dadd(uint2 a, uint2 b) { uint s = a.y >> 31; return s == (b.y >> 31) ? w_daddmags(a, b, s) : w_dsubmags(a, b, s); }
uint2 w_dsub(uint2 a, uint2 b) { uint s = a.y >> 31; return s == (b.y >> 31) ? w_dsubmags(a, b, s) : w_daddmags(a, b, s); }
// High 64 bits of a 128-bit product; sticky = 1 when the low 64 bits are not zero.
uint2 w_mul128hi(uint2 a, uint2 b, out uint sticky)
{
    uint2 p00 = w_mulu32(a.x, b.x), p01 = w_mulu32(a.x, b.y), p10 = w_mulu32(a.y, b.x), p11 = w_mulu32(a.y, b.y);
    uint2 mid = w_add64(w_add64(uint2(p00.y, 0u), uint2(p01.x, 0u)), uint2(p10.x, 0u));
    sticky = (p00.x | mid.x) != 0u ? 1u : 0u;
    return w_add64(w_add64(w_add64(p11, uint2(p01.y, 0u)), uint2(p10.y, 0u)), uint2(mid.y, 0u));
}
uint2 w_dmul(uint2 a, uint2 b)
{
    uint s = (a.y ^ b.y) >> 31;
    int ea = (int)w_dexp(a), eb = (int)w_dexp(b);
    uint2 ma = w_dfrac(a), mb = w_dfrac(b), r = uint2(0u, s << 31);
    if (w_disnan(a) || w_disnan(b)) r = w_dnan(a, b);
    else if (ea == 2047 || eb == 2047) r = w_dzero(a) || w_dzero(b) ? W_DNAN : w_dinf(s);
    else if (!w_dzero(a) && !w_dzero(b))
    {
        w_dnorm(ea, ma); w_dnorm(eb, mb);
        int ez = ea + eb - 1023;
        uint st;
        uint2 z = w_mul128hi(w_shl64(ma | uint2(0u, 0x00100000u), 10u), w_shl64(mb | uint2(0u, 0x00100000u), 11u), st);
        z.x |= st;
        if (z.y < 0x40000000u) { ez--; z = w_shl64(z, 1u); }
        r = w_dround(s, ez, z);
    }
    return r;
}
uint2 w_ddiv(uint2 a, uint2 b)
{
    uint s = (a.y ^ b.y) >> 31;
    int ea = (int)w_dexp(a), eb = (int)w_dexp(b);
    uint2 ma = w_dfrac(a), mb = w_dfrac(b), r = uint2(0u, s << 31);
    if (w_disnan(a) || w_disnan(b)) r = w_dnan(a, b);
    else if (ea == 2047) r = eb == 2047 ? W_DNAN : w_dinf(s);
    else if (eb == 2047) r = uint2(0u, s << 31);
    else if (w_dzero(b)) r = w_dzero(a) ? W_DNAN : w_dinf(s);
    else if (!w_dzero(a))
    {
        w_dnorm(ea, ma); w_dnorm(eb, mb);
        int ez = ea - eb + 1022;
        ma.y |= 0x00100000u; mb.y |= 0x00100000u;
        if (w_ltu64(ma, mb)) { ez--; ma = w_shl64(ma, 1u); }
        // Restoring division: 63 quotient bits, leading 1 at bit 62.
        uint2 q = uint2(0u, 0u);
        [loop] for (int i = 62; i >= 0; i--)
        {
            if (!w_ltu64(ma, mb)) { ma = w_sub64(ma, mb); if (i >= 32) q.y |= 1u << (uint)(i - 32); else q.x |= 1u << (uint)i; }
            ma = w_shl64(ma, 1u);
        }
        q.x |= w_nz64(ma) ? 1u : 0u;
        r = w_dround(s, ez, q);
    }
    return r;
}
uint2 w_dsqrt(uint2 a)
{
    int ea = (int)w_dexp(a);
    uint2 ma = w_dfrac(a), r = a;
    if (w_disnan(a)) r = a | uint2(0u, 0x00080000u);
    else if (w_dzero(a)) r = a;
    else if ((a.y >> 31) != 0u) r = W_DNAN;
    else if (ea != 2047)
    {
        w_dnorm(ea, ma);
        ma.y |= 0x00100000u;
        int e = ea - 1023;
        if ((e & 1) != 0) ma = w_shl64(ma, 1u);
        int ez = ((e - (e & 1)) >> 1) + 1022;
        // Digit-by-digit square root of ma << 56: 55 result bits.
        uint2 q = uint2(0u, 0u), rem = uint2(0u, 0u);
        [loop] for (int i = 0; i < 55; i++)
        {
            rem = w_shl64(rem, 2u);
            rem.x |= i <= 26 ? w_shru64(ma, (uint)(52 - 2 * i)).x & 3u : 0u;
            uint2 t = w_shl64(q, 2u) | uint2(1u, 0u);
            q = w_shl64(q, 1u);
            if (!w_ltu64(rem, t)) { rem = w_sub64(rem, t); q.x |= 1u; }
        }
        q = w_shl64(q, 8u);
        q.x |= w_nz64(rem) ? 1u : 0u;
        r = w_dround(0u, ez, q);
    }
    return r;
}
bool w_deq(uint2 a, uint2 b) { return !w_disnan(a) && !w_disnan(b) && (all(a == b) || (w_dzero(a) && w_dzero(b))); }
bool w_dlt(uint2 a, uint2 b)
{
    uint sa = a.y >> 31;
    bool lt = sa != (b.y >> 31) ? sa != 0u && !(w_dzero(a) && w_dzero(b)) : any(a != b) && ((sa != 0u) != w_ltu64(a, b));
    return !w_disnan(a) && !w_disnan(b) && lt;
}
bool w_dle(uint2 a, uint2 b) { return w_dlt(a, b) || w_deq(a, b); }
uint2 w_dmin(uint2 a, uint2 b) { return w_disnan(a) || w_disnan(b) ? w_dnan(a, b) : w_dlt(a, b) ? a : w_dlt(b, a) ? b : (a | b); }
uint2 w_dmax(uint2 a, uint2 b) { return w_disnan(a) || w_disnan(b) ? w_dnan(a, b) : w_dlt(a, b) ? b : w_dlt(b, a) ? a : (a & b); }
uint2 w_dabs(uint2 a) { return uint2(a.x, a.y & 0x7FFFFFFFu); }
uint2 w_dneg(uint2 a) { return uint2(a.x, a.y ^ 0x80000000u); }
uint2 w_dcopysign(uint2 a, uint2 b) { return uint2(a.x, (a.y & 0x7FFFFFFFu) | (b.y & 0x80000000u)); }
// Round to integral: mode 0 nearest even, 1 trunc, 2 floor, 3 ceil.
uint2 w_dint(uint2 a, uint mode)
{
    uint e = w_dexp(a), s = a.y >> 31;
    uint2 r = a;
    if (e <= 0x3FEu)
    {
        bool up = mode == 0u ? e == 0x3FEu && w_nz64(w_dfrac(a)) : mode == 2u ? s != 0u : mode == 3u ? s == 0u : false;
        r = w_dzero(a) ? a : up ? uint2(0u, (s << 31) | 0x3FF00000u) : uint2(0u, s << 31);
    }
    else if (e < 0x433u)
    {
        uint2 last = w_shl64(uint2(1u, 0u), 0x433u - e), mask = w_sub64(last, uint2(1u, 0u));
        if (mode == 0u) { r = w_add64(a, w_shru64(last, 1u)); if (!w_nz64(r & mask)) r &= ~last; }
        else if ((mode == 2u && s != 0u) || (mode == 3u && s == 0u)) r = w_add64(a, mask);
        r &= ~mask;
    }
    else if (w_disnan(a)) r.y |= 0x00080000u;
    return r;
}
uint2 w_dcvt_u64(uint2 a) { return a.y >= 0x80000000u ? w_dround(0u, 1085, w_jam64(a, 1u)) : w_dnormround(0u, 1084, a); }
uint2 w_dcvt_s64(uint2 a)
{
    uint s = a.y >> 31;
    return (a.x | (a.y & 0x7FFFFFFFu)) == 0u ? uint2(0u, s != 0u ? 0xC3E00000u : 0u) : w_dnormround(s, 1084, s != 0u ? w_neg64(a) : a);
}
