        void Result(FuncType ft, string call)
        {
            if (ft.Results.Length == 0) Line(call + ";");
            else if (ft.Results.Length == 1) Push(ft.Results[0], call);
            else throw new NotSupportedException("multi-value call results are not supported");
        }

        /// <summary>Skips an instruction's immediates in dead code.</summary>
        void SkipImmediates(byte op)
        {
            if (op >= 0x28 && op <= 0x3E) { if ((_r.U32() & 0x40) != 0) _r.U32(); _r.U32(); return; }
            switch (op)
            {
                case 0x0C: case 0x0D: case 0x10: case 0x20: case 0x21: case 0x22: case 0x23: case 0x24: case 0x25: case 0x26: _r.U32(); break;
                case 0x0E: for (uint n = _r.U32() + 1, k = 0; k < n; k++) _r.U32(); break;
                case 0x11: _r.U32(); _r.U32(); break;
                case 0x1C: for (uint n = _r.U32(), k = 0; k < n; k++) _r.Byte(); break;
                case 0x3F: case 0x40: _r.Byte(); break;
                case 0x41: _r.S64(); break;
                case 0x42: _r.S64(); break;
                case 0x43: _r.Pos += 4; break;
                case 0x44: _r.Pos += 8; break;
                case 0xFC:
                {
                    uint sub = _r.U32();
                    if (sub == 8) { _r.U32(); _r.U32(); }
                    else if (sub == 9 || sub == 11 || sub == 13 || sub == 15 || sub == 16 || sub == 17) _r.U32();
                    else if (sub == 10 || sub == 12 || sub == 14) { _r.U32(); _r.U32(); }
                    break;
                }
                case 0xD0: _r.Byte(); break;
                case 0xD2: _r.U32(); break;
                case 0xFD:
                {
                    uint sub = _r.U32();
                    if (sub <= 11 || sub == 92 || sub == 93) { if ((_r.U32() & 0x40) != 0) _r.U32(); _r.U32(); }
                    else if (sub >= 84 && sub <= 91) { if ((_r.U32() & 0x40) != 0) _r.U32(); _r.U32(); _r.Byte(); }
                    else if (sub == 12 || sub == 13) _r.Pos += 16;
                    else if (sub >= 21 && sub <= 34) _r.Byte();
                    break;
                }
            }
        }
