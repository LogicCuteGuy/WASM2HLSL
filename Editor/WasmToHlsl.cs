    /// <summary>
    /// Emits one function. The wasm operand stack becomes typed slot variables (s{depth}{type}).
    /// Loops become `[loop] for (;;)`. Blocks/ifs only become a single-pass loop when something nested inside
    /// them branches out to them; branches straight out of a block's own body become `if` guards instead,
    /// which keeps fxc compile times sane. Multi-level branches unwind through w_br (HLSL loops left to exit)
    /// and w_bm (0 exit, 1 continue, 2 return).
    /// </summary>
    internal sealed partial class FuncEmitter
    {
        enum Kind { Func, Block, Loop, If, Dead }

        sealed class Frame
        {
            public Kind Kind;
            public int Height;
            public WasmType[] Params = new WasmType[0], Results = new WasmType[0];
            public bool Unreachable, NeedsCheck, HlslLoop;
            public int Guards; // open `if` guards in the current arm
        }

        readonly WasmModule _m;
        readonly uint _index;
        readonly FuncType _type;
        readonly List<WasmType> _locals = new List<WasmType>();
        readonly List<WasmType> _stack = new List<WasmType>();
        readonly List<Frame> _ctrl = new List<Frame>();
        readonly List<string> _lines = new List<string>();
        readonly SortedSet<string> _slots = new SortedSet<string>(StringComparer.Ordinal);
        bool _usesBr;
        int _loops;
        int _opPos;
        HashSet<int> _loopBlocks;
        Reader _r;

        public readonly HashSet<uint> Callees = new HashSet<uint>();
        public readonly HashSet<ulong> Dispatches = new HashSet<ulong>();
        public string Text;
        readonly WasmToHlsl.TableUse _tables;

        public FuncEmitter(WasmModule m, uint index, WasmToHlsl.TableUse tables)
        {
            _m = m; _index = index; _type = m.TypeOfFunc(index); _tables = tables;
            if (_type.Results.Length > 1) throw new NotSupportedException("multi-value function results are not supported");
            _locals.AddRange(_type.Params);
            _locals.AddRange(m.Bodies[(int)(index - m.ImportedFuncCount)].Locals);
        }

        Frame Top => _ctrl[_ctrl.Count - 1];
        string Indent => new string(' ', 4 * (_ctrl.Count + _ctrl.Sum(f => f.Guards)));
        void Line(string s) => _lines.Add(Indent + s);

        static char Suffix(WasmType t) => t == WasmType.I32 ? 'i' : t == WasmType.I64 ? 'l' : t == WasmType.F32 ? 'f'
            : t == WasmType.F64 ? 'd' : t == WasmType.V128 ? 'v' : 'r';

        string Slot(int depth, WasmType t)
        {
            string n = $"s{depth}{Suffix(t)}";
            _slots.Add($"{WasmToHlsl.HT(t)} {n} = {WasmToHlsl.Zero(t)};");
            return n;
        }

        string Pop() { var t = _stack[_stack.Count - 1]; _stack.RemoveAt(_stack.Count - 1); return Slot(_stack.Count, t); }
        WasmType PeekType() => _stack[_stack.Count - 1];
        void Push(WasmType t, string expr) { Line($"{Slot(_stack.Count, t)} = {expr};"); _stack.Add(t); }

        void Un(WasmType r, string fmt) { var a = Pop(); Push(r, string.Format(fmt, a)); }
        void Bin(WasmType r, string fmt) { var b = Pop(); var a = Pop(); Push(r, string.Format(fmt, a, b)); }
        void Tern(WasmType r, string fmt) { var c = Pop(); var b = Pop(); var a = Pop(); Push(r, string.Format(fmt, a, b, c)); }

        public void Emit()
        {
            var body = _m.Bodies[(int)(_index - _m.ImportedFuncCount)];
            _loopBlocks = ScanLoopBlocks(body.Code);
            _r = new Reader(body.Code, 0);
            _ctrl.Add(new Frame { Kind = Kind.Func, Results = _type.Results });

            while (_ctrl.Count > 0)
            {
                _opPos = _r.Pos;
                byte op = _r.Byte();
                var top = Top;
                if (top.Kind == Kind.Dead || top.Unreachable)
                {
                    if (op == 0x02 || op == 0x03 || op == 0x04) { BlockType(); _ctrl.Add(new Frame { Kind = Kind.Dead }); continue; }
                    if (op == 0x0B && top.Kind == Kind.Dead) { _ctrl.RemoveAt(_ctrl.Count - 1); continue; }
                    if (op == 0x05 && top.Kind == Kind.Dead) continue;
                    if (op != 0x0B && op != 0x05) { SkipImmediates(op); continue; }
                }
                Op(op);
            }

            var sb = new StringBuilder();
            string ret = _type.Results.Length == 0 ? "void" : WasmToHlsl.HT(_type.Results[0]);
            var ps = string.Join(", ", _type.Params.Select((t, i) => $"{WasmToHlsl.HT(t)} l{i}"));
            sb.AppendLine($"{ret} f{_index}({ps})");
            sb.AppendLine("{");
            for (int i = _type.Params.Length; i < _locals.Count; i++)
                sb.AppendLine($"    {WasmToHlsl.HT(_locals[i])} l{i} = {WasmToHlsl.Zero(_locals[i])};");
            foreach (var s in _slots) sb.AppendLine("    " + s);
            if (_usesBr) sb.AppendLine("    uint w_br = 0u; uint w_bm = 0u;");
            for (int i = 0; i < _loops; i++) sb.AppendLine($"    uint w_it{i} = 0u;");
            foreach (var l in _lines) sb.AppendLine(l);
            sb.AppendLine("}");
            Text = sb.ToString();
        }

        WasmType[] BlockTypeResults, BlockTypeParams;

        void BlockType()
        {
            byte b = _body(0);
            if (b == 0x40) { _r.Pos++; BlockTypeParams = BlockTypeResults = new WasmType[0]; return; }
            if (b == 0x7F || b == 0x7E || b == 0x7D || b == 0x7C || b == 0x7B || b == 0x70 || b == 0x6F)
            { _r.Pos++; BlockTypeParams = new WasmType[0]; BlockTypeResults = new[] { (WasmType)b }; return; }
            var ft = _m.Types[(int)_r.S64()];
            BlockTypeParams = ft.Params; BlockTypeResults = ft.Results;
        }

        byte _body(int ahead) => _m.Bodies[(int)(_index - _m.ImportedFuncCount)].Code[_r.Pos + ahead];

        void MarkUnreachable() => Top.Unreachable = true;

        /// <summary>
        /// Pre-pass: block/if positions that are branched to from inside a nested construct, or from br_table.
        /// Only those need a breakable HLSL loop.
        /// </summary>
        HashSet<int> ScanLoopBlocks(byte[] code)
        {
            var result = new HashSet<int>();
            var stack = new List<int>(); // opcode position per open construct; -1 for func/loop
            stack.Add(-1);
            var saved = _r;
            _r = new Reader(code, 0);
            while (stack.Count > 0)
            {
                int pos = _r.Pos;
                byte op = _r.Byte();
                switch (op)
                {
                    case 0x02: case 0x04: BlockType(); stack.Add(pos); break;
                    case 0x03: BlockType(); stack.Add(-1); break;
                    case 0x0B: stack.RemoveAt(stack.Count - 1); break;
                    case 0x0C: case 0x0D:
                    {
                        int d = (int)_r.U32();
                        if (d > 0 && d < stack.Count && stack[stack.Count - 1 - d] >= 0) result.Add(stack[stack.Count - 1 - d]);
                        break;
                    }
                    case 0x0E:
                        for (uint n = _r.U32() + 1, k = 0; k < n; k++)
                        {
                            int d = (int)_r.U32();
                            if (d < stack.Count && stack[stack.Count - 1 - d] >= 0) result.Add(stack[stack.Count - 1 - d]);
                        }
                        break;
                    default: SkipImmediates(op); break;
                }
            }
            _r = saved;
            return result;
        }

        void OpenFrame(Kind k)
        {
            var f = new Frame { Kind = k, Params = BlockTypeParams, Results = BlockTypeResults, Height = _stack.Count - BlockTypeParams.Length };
            if (k == Kind.If && f.Params.Length > 0) throw new NotSupportedException("'if' with block parameters is not supported");
            f.HlslLoop = k == Kind.Loop || _loopBlocks.Contains(_opPos);
            // Always attribute loops: without it fxc tries (and fails) to unroll single-pass blocks holding breaks.
            // [fastopt] on single-pass blocks cuts compile time roughly in half.
            if (k == Kind.If)
            {
                var c = Pop(); f.Height = _stack.Count;
                Line(f.HlslLoop ? $"[fastopt] for (;;) {{ if ({c} != 0u) {{" : $"if ({c} != 0u) {{");
            }
            else if (k == Kind.Loop)
            {
                // Iteration guard: a runaway loop would hang the GPU (and the VRChat client); trap instead.
                string it = $"w_it{_loops++}";
                Line($"{it} = 0u;");
                Line("[loop] for (;;) {");
                _ctrl.Add(f);
                Line($"if (++{it} > W_MAX_LOOP_ITER) {{");
                EmitTrap();
                Line("}");
                return;
            }
            else Line(f.HlslLoop ? "[fastopt] for (;;) {" : "{");
            _ctrl.Add(f);
        }

        void CloseGuards()
        {
            var f = Top;
            while (f.Guards > 0) { f.Guards--; Line("}"); }
        }

        void CloseFrame()
        {
            CloseGuards();
            var f = Top;
            if (f.Kind == Kind.Func)
            {
                Line(ReturnStmt()); // also the landing point of unwound returns when the end is unreachable
                _ctrl.RemoveAt(_ctrl.Count - 1);
                return;
            }
            if (f.HlslLoop)
            {
                if (f.Kind == Kind.If) Line("}");
                Line("break;");
            }
            _ctrl.RemoveAt(_ctrl.Count - 1);
            Line("}");
            if (f.NeedsCheck)
                Line(!_ctrl.Any(x => x.HlslLoop) ? $"w_br = 0u; if (w_bm == 2u) {ReturnStmt()}"
                    : "if (w_br != 0u) { w_br--; if (w_br != 0u) break; if (w_bm == 1u) { w_bm = 0u; continue; } }");
            _stack.RemoveRange(f.Height, _stack.Count - f.Height);
            _stack.AddRange(f.Results);
        }

        // Returns always read slot 0: nested returns copy their value there and unwind with breaks, because
        // fxc compile time explodes on `return` inside loops.
        string ReturnStmt() => _type.Results.Length == 0 ? "return;" : $"return {Slot(0, _type.Results[0])};";

        /// <summary>HLSL loops between the innermost frame and frame index `depth` (exclusive).</summary>
        int LoopsInside(int depth)
        {
            int n = 0;
            for (int j = 0; j < depth; j++) if (_ctrl[_ctrl.Count - 1 - j].HlslLoop) n++;
            return n;
        }

        void Unwind(int exits, uint mode)
        {
            for (int j = 0, marked = 0; marked < exits; j++)
            {
                var f = _ctrl[_ctrl.Count - 1 - j];
                if (f.HlslLoop) { f.NeedsCheck = true; marked++; }
            }
            _usesBr = true;
            Line($"w_br = {exits}u; w_bm = {mode}u; break;");
        }

        void EmitTrap()
        {
            Line("w_trap = 1u;");
            int loops = LoopsInside(_ctrl.Count - 1);
            if (loops == 0) Line(ReturnStmt()); else Unwind(loops, 2);
        }

        /// <summary>True when `br depth` can be a guard: it leaves only the current, loop-free block.</summary>
        bool IsGuardBr(int depth) => depth == 0 && !Top.HlslLoop && (Top.Kind == Kind.Block || Top.Kind == Kind.If);

        string CarryCopies(int depth)
        {
            var t = _ctrl[_ctrl.Count - 1 - depth];
            var sb = new StringBuilder();
            if (t.Kind == Kind.Func)
            {
                if (_type.Results.Length > 0)
                {
                    string dst = Slot(0, _type.Results[0]), src = Slot(_stack.Count - 1, _type.Results[0]);
                    if (dst != src) sb.Append($"{dst} = {src}; ");
                }
                return sb.ToString();
            }
            var carried = t.Kind == Kind.Loop ? t.Params : t.Results;
            for (int j = 0; j < carried.Length; j++)
            {
                string dst = Slot(t.Height + j, carried[j]), src = Slot(_stack.Count - carried.Length + j, carried[j]);
                if (dst != src) sb.Append($"{dst} = {src}; ");
            }
            return sb.ToString();
        }

        /// <summary>Emits the jump for `br depth` without changing the compile-time stack.</summary>
        void EmitBr(int depth)
        {
            var t = _ctrl[_ctrl.Count - 1 - depth];
            string copies = CarryCopies(depth);
            if (copies.Length > 0) Line(copies.TrimEnd());
            int loops = LoopsInside(depth);
            if (t.Kind == Kind.Func) { if (loops == 0) Line(ReturnStmt()); else Unwind(loops, 2); return; }
            if (t.Kind == Kind.Loop) { if (loops == 0) Line("continue;"); else Unwind(loops, 1); return; }
            if (!t.HlslLoop) throw new InvalidOperationException("branch to a loop-free block from a nested construct");
            if (loops == 0) Line("break;"); else Unwind(loops + 1, 0);
        }

        string Addr(string a)
        {
            uint align = _r.U32();
            if ((align & 0x40) != 0 && _r.U32() != 0) throw new NotSupportedException("multi-memory is not supported");
            uint off = _r.U32();
            return off == 0 ? a : $"{a} + {off}u";
        }

        void Load(WasmType t, string fmt) { var a = Pop(); Push(t, string.Format(fmt, Addr(a))); }
        void Store(string fmt) { var v = Pop(); var a = Pop(); Line(string.Format(fmt, Addr(a), v) + ";"); }

        void Op(byte op)
        {
            const WasmType I = WasmType.I32, L = WasmType.I64, F = WasmType.F32, D = WasmType.F64;
            switch (op)
            {
                case 0x00: EmitTrap(); MarkUnreachable(); break;
                case 0x01: break;
                case 0x02: BlockType(); OpenFrame(Kind.Block); break;
                case 0x03: BlockType(); OpenFrame(Kind.Loop); break;
                case 0x04: BlockType(); OpenFrame(Kind.If); break;
                case 0x05:
                {
                    CloseGuards();
                    var f = Top;
                    _stack.RemoveRange(f.Height, _stack.Count - f.Height);
                    f.Unreachable = false;
                    _lines.Add(new string(' ', 4 * (_ctrl.Count - 1)) + "} else {");
                    break;
                }
                case 0x0B: CloseFrame(); break;
                case 0x0C:
                {
                    int depth = (int)_r.U32();
                    if (IsGuardBr(depth)) { string copies = CarryCopies(0); if (copies.Length > 0) Line(copies.TrimEnd()); }
                    else EmitBr(depth);
                    MarkUnreachable();
                    break;
                }
                case 0x0D:
                {
                    int depth = (int)_r.U32();
                    var c = Pop();
                    if (IsGuardBr(depth))
                    {
                        // Skip the rest of this block when taken: guard the remainder instead of breaking.
                        string copies = CarryCopies(0);
                        Line(copies.Length == 0 ? $"if ({c} == 0u) {{" : $"if ({c} != 0u) {{ {copies}}} else {{");
                        Top.Guards++;
                        break;
                    }
                    Line($"if ({c} != 0u) {{");
                    var before = _lines.Count;
                    EmitBr(depth);
                    for (int k = before; k < _lines.Count; k++) _lines[k] = "    " + _lines[k];
                    Line("}");
                    break;
                }
                case 0x0E:
                {
                    uint n = _r.U32();
                    var targets = new int[n];
                    for (int k = 0; k < n; k++) targets[k] = (int)_r.U32();
                    int def = (int)_r.U32();
                    var idx = Pop();
                    for (int k = 0; k <= n; k++)
                    {
                        Line(k == n ? (n == 0 ? "{" : "} else {") : (k == 0 ? $"if ({idx} == {k}u) {{" : $"}} else if ({idx} == {k}u) {{"));
                        int before = _lines.Count;
                        EmitBr(k == n ? def : targets[k]);
                        for (int j = before; j < _lines.Count; j++) _lines[j] = "    " + _lines[j];
                    }
                    Line("}");
                    MarkUnreachable();
                    break;
                }
                case 0x0F: EmitBr(_ctrl.Count - 1); MarkUnreachable(); break;
                case 0x10:
                {
                    uint fi = _r.U32();
                    var ft = _m.TypeOfFunc(fi);
                    var args = PopArgs(ft.Params.Length);
                    string call;
                    if (_m.FuncImport(fi) is Import imp) call = WasmToHlsl.ImportExpr(imp, ft, args);
                    else { call = $"f{fi}({string.Join(", ", args)})"; Callees.Add(fi); }
                    Result(ft, call);
                    break;
                }
                case 0x11:
                {
                    uint ti = _r.U32(), table = _r.U32();
                    var ft = _m.Types[(int)ti];
                    var i = Pop();
                    var args = PopArgs(ft.Params.Length);
                    Dispatches.Add(WasmToHlsl.DispatchKey(ti, table));
                    Result(ft, $"w_ci{ti}_{table}({string.Join("", new[] { i }.Concat(args).Select((a, k) => k == 0 ? a : ", " + a))})");
                    break;
                }
                case 0x1A: Pop(); break;
                case 0x1B: case 0x1C:
                {
                    if (op == 0x1C) for (uint n = _r.U32(), k = 0; k < n; k++) _r.Byte();
                    var c = Pop(); var t = _stack[_stack.Count - 2];
                    var b = Pop(); var a = Pop();
                    Push(t, $"({c} != 0u) ? {a} : {b}");
                    break;
                }
                case 0x20: { int i = (int)_r.U32(); Push(_locals[i], $"l{i}"); break; }
                case 0x21: { int i = (int)_r.U32(); Line($"l{i} = {Pop()};"); break; }
                case 0x22: { int i = (int)_r.U32(); Line($"l{i} = {Slot(_stack.Count - 1, PeekType())};"); break; }
                case 0x23: { int i = (int)_r.U32(); Push(_m.Globals[i].Type, $"g{i}"); break; }
                case 0x24: { int i = (int)_r.U32(); Line($"g{i} = {Pop()};"); break; }
                case 0x25: { uint t = _r.U32(); _tables.Used.Add(t); Un(_m.Tables[(int)t].Type, $"w_tget{t}({{0}})"); break; }
                case 0x26: { uint t = _r.U32(); _tables.Used.Add(t); _tables.Written.Add(t); var v = Pop(); Line($"w_tset{t}({Pop()}, {v});"); break; }

                case 0x28: Load(I, "w_ld32({0})"); break;
                case 0x29: Load(L, "w_ld64({0})"); break;
                case 0x2A: Load(F, "asfloat(w_ld32({0}))"); break;
                case 0x2B: Load(D, "w_ld64({0})"); break;
                case 0x2C: Load(I, "(uint)((int)(w_ld8({0}) << 24) >> 24)"); break;
                case 0x2D: Load(I, "w_ld8({0})"); break;
                case 0x2E: Load(I, "(uint)((int)(w_ld16({0}) << 16) >> 16)"); break;
                case 0x2F: Load(I, "w_ld16({0})"); break;
                case 0x30: Load(L, "w_sext64((uint)((int)(w_ld8({0}) << 24) >> 24))"); break;
                case 0x31: Load(L, "uint2(w_ld8({0}), 0u)"); break;
                case 0x32: Load(L, "w_sext64((uint)((int)(w_ld16({0}) << 16) >> 16))"); break;
                case 0x33: Load(L, "uint2(w_ld16({0}), 0u)"); break;
                case 0x34: Load(L, "w_sext64(w_ld32({0}))"); break;
                case 0x35: Load(L, "uint2(w_ld32({0}), 0u)"); break;
                case 0x36: Store("w_st32({0}, {1})"); break;
                case 0x37: Store("w_st64({0}, {1})"); break;
                case 0x38: Store("w_st32({0}, asuint({1}))"); break;
                case 0x39: Store("w_st64({0}, {1})"); break;
                case 0x3A: case 0x3C: Store(op == 0x3A ? "w_st8({0}, {1})" : "w_st8({0}, {1}.x)"); break;
                case 0x3B: case 0x3D: Store(op == 0x3B ? "w_st16({0}, {1})" : "w_st16({0}, {1}.x)"); break;
                case 0x3E: Store("w_st32({0}, {1}.x)"); break;
                case 0x3F: _r.Byte(); Push(I, "W_MEM_PAGES"); break;
                case 0x40: _r.Byte(); Pop(); Push(I, "0xFFFFFFFFu"); break; // memory.grow always fails

                case 0x41: Push(I, WasmToHlsl.Const(I, (uint)_r.S32())); break;
                case 0x42: Push(L, WasmToHlsl.Const(L, (ulong)_r.S64())); break;
                case 0x43: Push(F, WasmToHlsl.Const(F, _r.U32Fixed())); break;
                case 0x44: Push(D, WasmToHlsl.Const(D, _r.U64Fixed())); break;

                case 0x45: Un(I, "(uint)({0} == 0u)"); break;
                case 0x46: Bin(I, "(uint)({0} == {1})"); break;
                case 0x47: Bin(I, "(uint)({0} != {1})"); break;
                case 0x48: Bin(I, "(uint)((int){0} < (int){1})"); break;
                case 0x49: Bin(I, "(uint)({0} < {1})"); break;
                case 0x4A: Bin(I, "(uint)((int){0} > (int){1})"); break;
                case 0x4B: Bin(I, "(uint)({0} > {1})"); break;
                case 0x4C: Bin(I, "(uint)((int){0} <= (int){1})"); break;
                case 0x4D: Bin(I, "(uint)({0} <= {1})"); break;
                case 0x4E: Bin(I, "(uint)((int){0} >= (int){1})"); break;
                case 0x4F: Bin(I, "(uint)({0} >= {1})"); break;

                case 0x50: Un(I, "(uint)(({0}.x | {0}.y) == 0u)"); break;
                case 0x51: Bin(I, "(uint)all({0} == {1})"); break;
                case 0x52: Bin(I, "(uint)any({0} != {1})"); break;
                case 0x53: Bin(I, "(uint)w_lts64({0}, {1})"); break;
                case 0x54: Bin(I, "(uint)w_ltu64({0}, {1})"); break;
